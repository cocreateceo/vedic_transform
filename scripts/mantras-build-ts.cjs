// Converts scripts/mantras-master-list.json into a canonical
// src/data/mantras.ts that matches the schema used by /data/posters.ts.
//
// Produces:
//   - MantraCategory / MantraLengthClass type unions
//   - Mantra / MantraYantra / MantraText / MantraVideo interfaces
//   - MANTRAS array (24 entries)
//   - Lookup helpers: getMantraBySlug · getMantrasByPillar · getMantrasByCategory

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(__dirname, 'mantras-master-list.json');
const OUT = path.join(ROOT, 'src/data/mantras.ts');

const data = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const mantras = data.mantras;

function tsString(s) { return JSON.stringify(s); }

const head = `// 24 canonical Vedic mantras — generated from scripts/mantras-master-list.json
// via scripts/mantras-build-ts.cjs. Edit the JSON and re-run the script;
// do not edit this file by hand.
//
// Each entry pairs the chant (Devanagari + IAST + English) with a yantra
// brief for the production template, a one-line meaning, deeper context,
// recommended timing, and per-video chant counts so the master list
// doubles as the YouTube Shorts production manifest.

export type MantraCategory =
  | "foundational"
  | "solar"
  | "healing"
  | "invocation-devata"
  | "vishnu"
  | "knowledge"
  | "abundance"
  | "protection"
  | "courage"
  | "universal-peace"
  | "daily-ritual"
  | "brahman";

export type MantraLengthClass = "short" | "medium" | "long";

export interface MantraYantra {
  /** Traditional name of the yantra (Sri Yantra, Ganesha Yantra, etc.). */
  name: string;
  /** Plain-English visual brief for the AE / Lottie template designer. */
  visualBrief: string;
}

export interface MantraText {
  devanagari: string;
  iast: string;
  /** Short English translation suitable for an on-screen subtitle. */
  english: string;
}

export interface MantraVideo {
  lengthClass: MantraLengthClass;
  /** Length of ONE recitation of the mantra, in seconds. */
  chantDurationSec: number;
  /** How many times the mantra is chanted in the short. */
  repetitions: number;
  /** Target finished length of the YouTube short, in seconds. */
  videoTargetSec: number;
}

export interface Mantra {
  slug: string;
  title: string;
  sanskritName: string;
  category: MantraCategory;
  devata: string;
  yantra: MantraYantra;
  text: MantraText;
  /** One-sentence summary suitable for a card preview. */
  meaningOneLine: string;
  /** 2-4 sentence deeper explanation surfacing on the detail card. */
  context: string;
  whenToChant: string;
  /** Optional pillar slug — surfaces this mantra on the matching pillar page. */
  pillarSlug?: string;
  video: MantraVideo;
}

export const MANTRAS: Mantra[] = [
`;

function emit(m) {
  const pillarLine = m.pillarSlug ? `    pillarSlug: ${tsString(m.pillarSlug)},\n` : '';
  return `  {
    slug: ${tsString(m.slug)},
    title: ${tsString(m.title)},
    sanskritName: ${tsString(m.sanskritName)},
    category: ${tsString(m.category)},
    devata: ${tsString(m.devata)},
    yantra: {
      name: ${tsString(m.yantra.name)},
      visualBrief:
        ${tsString(m.yantra.visualBrief)},
    },
    text: {
      devanagari: ${tsString(m.text.devanagari)},
      iast: ${tsString(m.text.iast)},
      english: ${tsString(m.text.english)},
    },
    meaningOneLine:
      ${tsString(m.meaningOneLine)},
    context:
      ${tsString(m.context)},
    whenToChant: ${tsString(m.whenToChant)},
${pillarLine}    video: {
      lengthClass: ${tsString(m.video.lengthClass)},
      chantDurationSec: ${m.video.chantDurationSec},
      repetitions: ${m.video.repetitions},
      videoTargetSec: ${m.video.videoTargetSec},
    },
  }`;
}

const body = mantras.map(emit).join(',\n');

const tail = `,
];

export function getMantraBySlug(slug: string): Mantra | undefined {
  return MANTRAS.find((m) => m.slug === slug);
}

export function getMantrasByPillar(pillarSlug: string): Mantra[] {
  return MANTRAS.filter((m) => m.pillarSlug === pillarSlug);
}

export function getMantrasByCategory(category: MantraCategory): Mantra[] {
  return MANTRAS.filter((m) => m.category === category);
}
`;

fs.writeFileSync(OUT, head + body + tail);
console.log('wrote ' + OUT);
console.log('mantras: ' + mantras.length);
console.log('lines: ' + (head + body + tail).split('\n').length);
